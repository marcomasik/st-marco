// Traces a photographed marker drawing (black ink on white paper) into SVG path data.
//
//   node scripts/trace-drawing.mjs <photo> <output.ts> [--rotate=-90] [--threshold=150]
//
// The photo is turned to black and white (light grid lines and paper texture drop out),
// trimmed to the ink, then traced with potrace. The output is a small TypeScript module with
// the path and its size, so a component can draw it in the site's colours.

import { writeFileSync } from 'node:fs';
import { promisify } from 'node:util';
import potrace from 'potrace';
import sharp from 'sharp';

const [input, output, ...flags] = process.argv.slice(2);
if (!input || !output) {
  console.error(
    'Usage: node scripts/trace-drawing.mjs <photo> <output.ts> [--rotate=-90] [--threshold=150]',
  );
  process.exit(1);
}
const option = (name, fallback) =>
  Number(flags.find((f) => f.startsWith(`--${name}=`))?.split('=')[1] ?? fallback);

const rotate = option('rotate', 0);
const threshold = option('threshold', 150);
const WIDTH = 1600;

// Black and white, trimmed to the ink with a little margin.
const ink = await sharp(input)
  .rotate(rotate)
  .flatten({ background: '#ffffff' })
  .greyscale()
  .threshold(threshold)
  .trim({ background: '#ffffff', threshold: 10 })
  .resize({ width: WIDTH, withoutEnlargement: false })
  .extend({ top: 12, bottom: 12, left: 12, right: 12, background: '#ffffff' })
  .png()
  .toBuffer();

const tracer = new potrace.Potrace({
  threshold: 128,
  turdSize: 60, // drop specks smaller than this (px²)
  optTolerance: 0.35,
  alphaMax: 1,
});
await promisify(tracer.loadImage.bind(tracer))(ink);
const traced = /\sd="([^"]+)"/.exec(tracer.getPathTag())?.[1];
if (!traced) throw new Error('Nothing traced: check the photo and the threshold.');

// Crop to the traced ink (specks left at the paper's edge can defeat the image trim): take
// the bounding box of all path points and move the path to start at the margin.
const MARGIN = 8;
const numbers = traced.match(/-?\d+(?:\.\d+)?/g).map(Number);
const xs = numbers.filter((_, i) => i % 2 === 0);
const ys = numbers.filter((_, i) => i % 2 === 1);
const minX = Math.min(...xs) - MARGIN;
const minY = Math.min(...ys) - MARGIN;
const cropWidth = Math.ceil(Math.max(...xs) - minX + MARGIN);
const cropHeight = Math.ceil(Math.max(...ys) - minY + MARGIN);
let index = 0;
const d = traced.replace(/-?\d+(?:\.\d+)?/g, (value) => {
  const shifted = Number(value) - (index++ % 2 === 0 ? minX : minY);
  return String(Math.round(shifted * 10) / 10);
});

writeFileSync(
  output,
  `// Generated by scripts/trace-drawing.mjs from ${input} (rotate ${rotate}, threshold ${threshold}).
// Regenerate instead of editing by hand.

export const WIDTH = ${cropWidth};
export const HEIGHT = ${cropHeight};
export const PATH =
  '${d.trim().replace(/\s+/g, ' ')}';
`,
);
console.log(
  `Traced ${input}: ${cropWidth} x ${cropHeight}, path ${(d.length / 1024).toFixed(1)} KB -> ${output}`,
);
